const BRAND_LOOKUPS = BRANDS
  .flatMap((brand) => brand.suffixes.map((suffix) => ({ ...brand, suffix })))
  .sort((a, b) => b.suffix.length - a.suffix.length)

export function stripHostPort(value: string): string {
  const trimmed = String(value || '').trim()
  if (!trimmed) return ''

  if (trimmed.startsWith('[')) {
    const end = trimmed.indexOf(']')
    if (end > 1) return trimmed.slice(1, end)
  }

  const colonCount = trimmed.split(':').length - 1
  if (colonCount === 1) {
    return trimmed.slice(0, trimmed.lastIndexOf(':'))
  }

  return trimmed.replace(/\.$/, '')
}

export function connectionDomain(connection: { metadata?: ClashConnectionMetadata } | null | undefined): string {
  const metadata = connection?.metadata || {}
  const raw = metadata.host
    || metadata.sniffHost
    || metadata.remoteDestination
    || metadata.destinationIP
    || metadata.destination
    || ''
  return stripHostPort(raw) || 'unknown'
}

export function normalizeDomain(domain: string): string {
  return String(domain || '')
    .trim()
    .toLowerCase()
    .replace(/\.$/, '')
    .replace(/^www\./, '')
}

function isIpAddress(value: string): boolean {
  if (/^\d{1,3}(?:\.\d{1,3}){3}$/.test(value)) return true
  return value.includes(':')
}

// 常见二级公共后缀：这些后缀的主域名要保留三段（例：foo.com.cn → foo.com.cn 而非 com.cn）
const COMPOUND_SUFFIXES = new Set<string>([
  'com.cn', 'net.cn', 'org.cn', 'gov.cn', 'edu.cn',
  'com.hk', 'com.tw', 'co.jp', 'or.jp', 'ne.jp',
  'co.uk', 'org.uk', 'com.au', 'com.sg', 'co.kr', 'com.br', 'co.in',
])

// 展示用主域名：去掉二级及以上子域（mercury.jd.com → jd.com）；IP/单段原样返回
export function mainDomain(domain: string): string {
  const normalized = normalizeDomain(domain)
  if (!normalized || normalized === 'unknown' || isIpAddress(normalized)) return normalized || domain
  const labels = normalized.split('.')
  if (labels.length <= 2) return normalized
  const lastTwo = labels.slice(-2).join('.')
  if (COMPOUND_SUFFIXES.has(lastTwo)) return labels.slice(-3).join('.')
  return lastTwo
}

function letterFromDomain(domain: string): string {
  const normalized = normalizeDomain(domain)
  const source = normalized === 'unknown' ? domain : normalized
  const match = String(source || '').match(/[a-z0-9]/i)
  return (match ? match[0] : '?').toUpperCase()
}

export function iconForDomain(domain: string): SiteIcon {
  const normalized = normalizeDomain(domain)
  if (!normalized || normalized === 'unknown' || isIpAddress(normalized)) {
    return {
      id: 'letter',
      label: domain || 'unknown',
      letter: letterFromDomain(domain),
    }
  }

  const brand = BRAND_LOOKUPS.find(({ suffix }) => (
    normalized === suffix || normalized.endsWith(`.${suffix}`)
  ))

  if (!brand) {
    return {
      id: 'letter',
      label: domain,
      letter: letterFromDomain(domain),
    }
  }

  return {
    id: brand.id,
    label: brand.label,
    background: brand.background,
    color: brand.color,
    path: brand.path,
    viewBox: '0 0 24 24',
  }
}
