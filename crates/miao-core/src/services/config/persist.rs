    #[tokio::test]
    async fn volatile_config_roundtrip_and_fallbacks() {
        use crate::models::{NodeSelect, Region, RouteMode, VolatileConfig};

        let temp_dir = std::env::temp_dir().join(format!("miao-volatile-{}", std::process::id()));
        let path = temp_dir.join("volatile.yaml");
        tokio::fs::create_dir_all(&temp_dir).await.unwrap();

        // 缺失 / 损坏都读不出（None = 不覆盖 config.yaml）
        assert!(load_volatile_config_at(&path).await.is_none());
        tokio::fs::write(&path, b"route_mode: [not-a-mode]")
            .await
            .unwrap();
        assert!(load_volatile_config_at(&path).await.is_none());

        let volatile = VolatileConfig {
            node_select: NodeSelect::Fastest(Region::Sg),
            route_mode: RouteMode::Global,
            ..VolatileConfig::default()
        };
        save_volatile_to(&path, &volatile).await.unwrap();
        assert!(!temp_dir.join("volatile.tmp").exists());
        let loaded = load_volatile_config_at(&path).await.unwrap();
        assert_eq!(loaded, volatile);

        // 未变化时跳过写入：内容不变且不产生临时文件
        save_volatile_to(&path, &volatile).await.unwrap();
        assert!(!temp_dir.join("volatile.tmp").exists());

        let _ = tokio::fs::remove_dir_all(&temp_dir).await;
    }

    #[tokio::test]
    async fn save_config_layered_rolls_back_stable_on_volatile_failure() {
        use crate::models::{Config, NodeSelect, Region};
        use crate::state::AppState;

        let base = std::env::temp_dir().join(format!(
            "miao-layered-fail-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        tokio::fs::create_dir_all(&base).await.unwrap();
        let config_path = base.join("config.yaml");
        let volatile_path = base.join("volatile.yaml");
        // 故障注入：volatile_path 是目录，写入必失败
        tokio::fs::create_dir_all(&volatile_path).await.unwrap();

        let make_state = || {
            std::sync::Arc::new(
                AppState::with_config_path(
                    Config::default(),
                    config_path.clone(),
                    volatile_path.clone(),
                )
                .unwrap(),
            )
        };
        let new_config = Config {
            subs: vec!["https://a.example.com".to_string()],
            node_select: NodeSelect::Fastest(Region::Hk),
            ..Config::default()
        };

        // 情形 1：稳定层原本不存在 → 失败后仍不存在
        let state = make_state();
        assert!(save_config_layered(&state, &new_config).await.is_err());
        assert!(
            !config_path.exists(),
            "stable layer should be rolled back (removed)"
        );

        // 情形 2：稳定层有旧内容 → 失败后旧内容逐字节保留
        let old_yaml = "subs:\n- https://old.example.com\n";
        tokio::fs::write(&config_path, old_yaml).await.unwrap();
        let state = make_state();
        assert!(save_config_layered(&state, &new_config).await.is_err());
        let after = tokio::fs::read_to_string(&config_path).await.unwrap();
        assert_eq!(after, old_yaml, "stable layer should keep old bytes");

        let _ = tokio::fs::remove_dir_all(&base).await;
    }

